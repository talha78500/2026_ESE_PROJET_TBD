static void RobotTask(void *arg){
    (void)arg;
    for (;;){
        shell_process();
        ota_process();
        motor_update();
        power_button_process();
        vTaskDelay(pdMS_TO_TICKS(5));
    }
}

void App_FreeRTOS_Start(void){
    BaseType_t result;

    result = xTaskCreate(RobotTask,"robot",1024,NULL,tskIDLE_PRIORITY + 1,NULL);
    if (result != pdPASS)	printf("ERREUR creation RobotTask\r\n");
    else					printf("RobotTask creee\r\n");
}
