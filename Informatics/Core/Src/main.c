static void console_tx_all(const uint8_t *data, uint16_t len)
{
	HAL_UART_Transmit(&huart2, (uint8_t *)data, len, HAL_MAX_DELAY);
	HAL_UART_Transmit(&huart3, (uint8_t *)data, len, HAL_MAX_DELAY);
}

int __io_putchar(int ch)
{
	uint8_t c = (uint8_t)ch;
	console_tx_all(&c, 1);
	return ch;
}

int _write(int file, char *ptr, int len) {
	(void)file;
	if (ptr != NULL && len > 0) {
		console_tx_all((const uint8_t *)ptr, (uint16_t)len);
	}
	return len;
}

void uart3_printf(const char *format, ...)
{
    char buffer[128]; // Ajustez la taille selon la longueur max de vos messages
    va_list args;

    va_start(args, format);
    int len = vsnprintf(buffer, sizeof(buffer), format, args);
    va_end(args);

    if (len > 0) {
        // S'assurer de ne pas dépasser la taille du buffer en cas de troncature
        uint16_t tx_len = (len < sizeof(buffer)) ? len : (sizeof(buffer) - 1);
        HAL_UART_Transmit(&huart3, (uint8_t *)buffer, tx_len, HAL_MAX_DELAY);
    }
}

